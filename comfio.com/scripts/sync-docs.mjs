#!/usr/bin/env node
/**
 * sync-docs.mjs — Reads markdown files from ../docs/ and generates
 * src/content/docs.ts with all doc content as a typed data structure.
 *
 * Run: npm run sync-docs
 */

import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "fs";
import { join, relative, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, "..");
const docsRoot = join(projectRoot, "..", "docs");
const outputPath = join(projectRoot, "src", "content", "docs.ts");

function walkDir(dir, base = "") {
  const entries = [];
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    const relPath = base ? `${base}/${entry}` : entry;
    const stat = statSync(fullPath);
    if (stat.isDirectory()) {
      entries.push(...walkDir(fullPath, relPath));
    } else if (entry.endsWith(".md") || entry.endsWith(".ipynb")) {
      entries.push({ relPath, fullPath });
    }
  }
  return entries;
}

function slugify(path) {
  return path.replace(/\.md$/, "").replace(/\.ipynb$/, "");
}

function getSection(relPath) {
  const parts = relPath.split("/");
  if (parts.length === 1) return "root";
  return parts[0]; // tutorials, how_to, theory, reference
}

function getSlug(relPath) {
  const parts = relPath.split("/");
  if (parts.length === 1) return slugify(parts[0]);
  return slugify(parts.slice(1).join("/"));
}

console.log("Reading docs from:", docsRoot);
const files = walkDir(docsRoot);
console.log(`Found ${files.length} doc files`);

const docsData = {};

for (const file of files) {
  const content = readFileSync(file.fullPath, "utf-8");
  const section = getSection(file.relPath);
  const slug = getSlug(file.relPath);

  if (section === "root") {
    // index.md, guide.md — skip for now
    continue;
  }

  if (!docsData[section]) {
    docsData[section] = {};
  }

  docsData[section][slug] = content;
}

// Generate TypeScript
const tsContent = `// AUTO-GENERATED by sync-docs.mjs — do not edit manually.
// Run \`npm run sync-docs\` to regenerate from ../docs/

export interface DocContent {
  [slug: string]: string;
}

export interface SectionContent {
  [section: string]: DocContent;
}

export const docsContent: SectionContent = ${JSON.stringify(docsData, null, 2)};

export function getDocContent(section: string, slug: string): string | undefined {
  return docsContent[section]?.[slug];
}
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, tsContent, "utf-8");
console.log(`Written: ${outputPath}`);
console.log(`Sections: ${Object.keys(docsData).join(", ")}`);
for (const [section, docs] of Object.entries(docsData)) {
  console.log(`  ${section}: ${Object.keys(docs).length} docs`);
}
