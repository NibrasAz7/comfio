"""Tests for the rectangular-room MRT domain (Task 4).

Regression fractions were generated by running the original
``compute_enclosure_factors`` (Hottel branch) from the MIT-licensed
``mrt_replication`` project and normalising by the factor sum.
"""

from __future__ import annotations

import numpy as np
import pytest

from comfio.domains.thermal_mrt import (
    SURFACES,
    Room,
    Window,
    mrt_grid,
    mrt_point,
    solar_delta_mrt,
    view_factors,
)


def _room(
    length: float = 7.2,
    width: float = 6.3,
    height: float = 3.0,
    temps: dict[str, float] | None = None,
    windows: list[Window] | None = None,
) -> Room:
    return Room(
        length=length,
        width=width,
        height=height,
        surface_temps=temps or dict.fromkeys(SURFACES, 22.0),
        windows=tuple(windows or ()),
    )


def test_uniform_room_mrt_equals_surface_temp() -> None:
    room = _room()
    for x, y, z in [(3.6, 3.15, 0.6), (0.1, 0.1, 1.1), (7.0, 6.0, 1.5)]:
        assert mrt_point(room, x, y, z) == pytest.approx(22.0, abs=1e-6)


def test_cube_centre_factors_equal() -> None:
    room = _room(length=2.0, width=2.0, height=2.0)
    f = view_factors(room, 1.0, 1.0, 1.0)
    assert set(f) == set(SURFACES)
    for s in SURFACES:
        assert f[s] == pytest.approx(1.0 / 6.0, abs=1e-6)
    assert sum(f.values()) == pytest.approx(1.0, abs=1e-9)


def test_view_factors_sum_to_one() -> None:
    room = _room()
    for point in [(3.6, 3.15, 0.6), (1.0, 1.0, 0.6), (7.2, 6.3, 2.9)]:
        f = view_factors(room, *point)
        assert sum(f.values()) == pytest.approx(1.0, abs=1e-9)
        assert all(v >= 0.0 for v in f.values())


def test_hot_wall_closer_is_warmer() -> None:
    temps = dict.fromkeys(SURFACES, 20.0)
    temps["front"] = 40.0
    room = _room(temps=temps)
    near = mrt_point(room, 1.0, 3.15, 0.6)
    mid = mrt_point(room, 3.6, 3.15, 0.6)
    far = mrt_point(room, 6.5, 3.15, 0.6)
    assert near > mid > far


def test_window_conserves_parent_factor() -> None:
    win = Window(wall="front", u0=1.0, z0=0.8, width=2.0, height=1.5, temp_c=30.0)
    bare = view_factors(_room(), 3.6, 3.15, 0.6)
    with_win = view_factors(_room(windows=[win]), 3.6, 3.15, 0.6)
    # the window splits off part of its parent wall — sum is conserved
    assert with_win["front"] + with_win["window:0"] == pytest.approx(bare["front"], abs=1e-9)
    assert sum(with_win.values()) == pytest.approx(1.0, abs=1e-9)
    for s in SURFACES:
        if s != "front":
            assert with_win[s] == pytest.approx(bare[s], abs=1e-9)


def test_window_same_temp_leaves_mrt_unchanged() -> None:
    win = Window(wall="left", u0=2.0, z0=0.9, width=1.5, height=1.2, temp_c=22.0)
    base = mrt_point(_room(), 3.6, 3.15, 0.6)
    with_win = mrt_point(_room(windows=[win]), 3.6, 3.15, 0.6)
    assert with_win == pytest.approx(base, abs=1e-9)


def test_window_changes_mrt_when_temps_differ() -> None:
    win = Window(wall="front", u0=1.0, z0=0.5, width=4.0, height=2.0, temp_c=35.0)
    base = mrt_point(_room(), 2.0, 3.15, 0.6)
    warmed = mrt_point(_room(windows=[win]), 2.0, 3.15, 0.6)
    assert warmed > base


def test_matches_replication_reference() -> None:
    room = _room()
    refs: dict[tuple[float, float, float], dict[str, float]] = {
        (3.6, 3.15, 0.6): {
            "front": 0.094020,
            "rear": 0.094020,
            "left": 0.115392,
            "right": 0.115392,
            "floor": 0.336812,
            "ceiling": 0.244364,
        },
        (1.0, 1.0, 0.6): {
            "front": 0.222702,
            "rear": 0.038565,
            "left": 0.222947,
            "right": 0.050318,
            "floor": 0.306677,
            "ceiling": 0.158792,
        },
        (6.0, 5.0, 1.1): {
            "front": 0.041334,
            "rear": 0.229944,
            "left": 0.055639,
            "right": 0.216204,
            "floor": 0.259528,
            "ceiling": 0.197351,
        },
    }
    for (x, y, z), expected in refs.items():
        f = view_factors(room, x, y, z)
        for surf, frac in expected.items():
            assert f[surf] == pytest.approx(frac, abs=1e-6), f"{surf} at {(x, y, z)}"


def test_invalid_dims_raise() -> None:
    with pytest.raises(ValueError, match="length"):
        _room(length=0.0)
    with pytest.raises(ValueError, match="width"):
        _room(width=-1.0)
    with pytest.raises(ValueError, match="height"):
        _room(height=0.0)


def test_missing_surface_temp_raises() -> None:
    with pytest.raises(ValueError, match="surface_temps"):
        _room(temps={"front": 20.0})


def test_point_outside_raises() -> None:
    room = _room()
    with pytest.raises(ValueError, match="x"):
        view_factors(room, -0.1, 3.0, 1.0)
    with pytest.raises(ValueError, match="y"):
        view_factors(room, 3.0, 7.0, 1.0)
    with pytest.raises(ValueError, match="z"):
        view_factors(room, 3.0, 3.0, 3.1)
    with pytest.raises(ValueError, match="x"):
        mrt_point(room, 8.0, 3.0, 1.0)


def test_point_on_wall_does_not_crash() -> None:
    room = _room()
    f = view_factors(room, 0.0, 3.15, 1.0)
    assert sum(f.values()) == pytest.approx(1.0, abs=1e-9)
    assert np.isfinite(mrt_point(room, 0.0, 3.15, 1.0))
    assert np.isfinite(mrt_point(room, 3.6, 3.15, 0.0))


def test_window_out_of_bounds_raises() -> None:
    # front wall extent = room width (6.3): u0 5.5 + w 2.0 = 7.5
    with pytest.raises(ValueError, match="u0|width"):
        _room(windows=[Window("front", u0=5.5, z0=0.5, width=2.0, height=1.0, temp_c=30.0)])
    # z0 2.5 + h 1.0 = 3.5 > room height 3.0
    with pytest.raises(ValueError, match="z0|height"):
        _room(windows=[Window("left", u0=1.0, z0=2.5, width=1.0, height=1.0, temp_c=30.0)])
    # negative u0 puts the window off the wall
    with pytest.raises(ValueError, match="u0"):
        _room(windows=[Window("rear", u0=-0.5, z0=0.5, width=1.0, height=1.0, temp_c=30.0)])


def test_bad_window_fields_raise() -> None:
    with pytest.raises(ValueError, match="wall"):
        Window("floor", u0=0.0, z0=0.0, width=1.0, height=1.0, temp_c=20.0)  # type: ignore[arg-type]
    with pytest.raises(ValueError, match="width"):
        Window("front", u0=0.0, z0=0.0, width=0.0, height=1.0, temp_c=20.0)
    with pytest.raises(ValueError, match="height"):
        Window("front", u0=0.0, z0=0.0, width=1.0, height=-1.0, temp_c=20.0)


def test_overlapping_windows_raise() -> None:
    a = Window("rear", u0=1.0, z0=0.5, width=2.0, height=1.5, temp_c=30.0)
    b = Window("rear", u0=2.0, z0=1.0, width=2.0, height=1.5, temp_c=30.0)
    other_wall = Window("front", u0=2.0, z0=1.0, width=2.0, height=1.5, temp_c=30.0)
    with pytest.raises(ValueError, match="overlap"):
        _room(windows=[a, b])
    # same wall but only edge-adjacent is fine
    adjacent = Window("rear", u0=3.0, z0=0.5, width=2.0, height=1.5, temp_c=30.0)
    _room(windows=[a, adjacent])
    # same footprint on a different wall is fine
    _room(windows=[b, other_wall])


def test_solar_delta_mrt_zero_and_positive() -> None:
    win = Window("front", u0=1.0, z0=0.8, width=2.0, height=1.5, temp_c=22.0)
    assert solar_delta_mrt(
        win,
        2.0,
        sol_altitude=45.0,
        sharp=0.0,
        sol_radiation_dir=0.0,
        sol_transmittance=0.7,
        f_bes=0.5,
    ) == pytest.approx(0.0, abs=0.05)
    assert solar_delta_mrt(
        win,
        2.0,
        sol_altitude=45.0,
        sharp=0.0,
        sol_radiation_dir=800.0,
        sol_transmittance=0.0,
        f_bes=0.5,
    ) == pytest.approx(0.0, abs=0.05)
    delta = solar_delta_mrt(
        win,
        1.0,
        sol_altitude=45.0,
        sharp=0.0,
        sol_radiation_dir=800.0,
        sol_transmittance=0.7,
        f_bes=0.5,
    )
    assert delta > 0.0
    # occupant flush against the window must not divide by zero
    assert (
        solar_delta_mrt(
            win,
            0.0,
            sol_altitude=45.0,
            sharp=0.0,
            sol_radiation_dir=800.0,
            sol_transmittance=0.7,
            f_bes=0.5,
        )
        >= 0.0
    )


def test_mrt_grid_shape_and_spacing() -> None:
    room = _room(length=6.0, width=5.0, height=3.0)
    xs, ys, grid = mrt_grid(room, posture="seated", spacing=0.5, margin=0.5)
    assert grid.shape == (len(ys), len(xs))
    assert len(xs) == 11 and len(ys) == 9
    assert np.diff(xs) == pytest.approx(0.5)
    assert np.diff(ys) == pytest.approx(0.5)
    assert xs[0] == pytest.approx(0.5) and xs[-1] <= 5.5
    # uniform 22 °C room -> every cell is 22
    assert grid == pytest.approx(22.0, abs=1e-6)


def test_mrt_grid_validation() -> None:
    room = _room(length=6.0, width=5.0, height=3.0)
    with pytest.raises(ValueError, match="posture"):
        mrt_grid(room, posture="lying")  # type: ignore[arg-type]
    with pytest.raises(ValueError, match="spacing"):
        mrt_grid(room, spacing=0.0)
    with pytest.raises(ValueError, match="margin"):
        mrt_grid(room, spacing=0.5, margin=3.0)
